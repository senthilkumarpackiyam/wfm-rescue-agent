"""Phase 4 checkpoint: full agent days with a supervisor, scored on the *real* outcome.

1. Five different kinds of bad day, auto-approved: does the agent recover service level?
2. The demo's human moment: reject the first recommendation with "no overtime budget today";
   the agent must re-plan without overtime.
Writes docs/phase4_results.md.

Run:  uv run python scripts/phase4_run.py        (WFM_LLM_MODE=cached to replay for free)
"""

from __future__ import annotations

from wfm.agent.llm import LLM
from wfm.agent.session import AutoApprove, DaySession, ScriptedSupervisor
from wfm.config import ROOT
from wfm.data.scenarios import get_scenario
from wfm.schemas import OfferOvertime
from wfm.sim.day import run_day

OUT = ROOT / "docs" / "phase4_results.md"
DAYS = ["OUT-01", "MKT-01", "SCK-02", "AHT-01", "WTH-02"]
REJECTION = "no overtime budget today"


def run_one(sid: str, llm: LLM, supervisor) -> dict:
    before = (llm.usage.cost_usd + llm.replayed.cost_usd, llm.usage.calls + llm.replayed.calls)
    s = DaySession(sid, llm, supervisor).run()
    base = run_day(sid).summary(s.first_alert or "08:00")
    got = s.outcome()
    s.save_log()
    return dict(sid=sid, session=s, base=base, got=got,
                claude_usd=round(llm.usage.cost_usd + llm.replayed.cost_usd - before[0], 2),
                claude_calls=llm.usage.calls + llm.replayed.calls - before[1])


def trace(s: DaySession) -> list[str]:
    lines = []
    for e in s.log:
        if e.step in ("detect",):
            continue
        text = e.summary.replace("\n", " ")
        lines.append(f"- **{e.at} {e.step}**: {text[:420]}{'...' if len(text) > 420 else ''}")
    return lines


def main() -> None:
    llm = LLM()
    rows = []
    for sid in DAYS:
        r = run_one(sid, llm, AutoApprove())
        rows.append(r)
        if r["session"].llm_errors:
            print(f"{sid}: INCOMPLETE - {r['session'].llm_errors[0]}")
        print(f"{sid}: alert {r['session'].first_alert} | SL {r['base'].service_level_pct} -> {r['got'].service_level_pct} "
              f"| abandon {r['base'].abandon_rate_pct} -> {r['got'].abandon_rate_pct} | Rs {r['got'].action_cost_inr:,.0f} "
              f"| rounds {r['session'].plans_made} | Claude ${r['claude_usd']}")

    demo = run_one("OUT-01", llm, ScriptedSupervisor([("reject", REJECTION)]))
    ds = demo["session"]
    ot_after = [a for a in ds.applied if isinstance(a.action, OfferOvertime)]
    print(f"DEMO reject: constraints {ds.constraints.model_dump(exclude_defaults=True, exclude={'notes'})} | "
          f"overtime actions applied: {len(ot_after)} | SL {demo['base'].service_level_pct} -> {demo['got'].service_level_pct}")

    incomplete = [r["sid"] for r in rows + [demo] if r["session"].llm_errors]
    if incomplete:
        print(f"Claude was unavailable on {incomplete}; results for those days are not valid.")
    recovered = [r for r in rows if r["got"].service_level_pct >= r["base"].service_level_pct + 5]
    lines = [
        "# Phase 4 results: plan, approve, execute, monitor",
        "",
        "Generated by `uv run python scripts/phase4_run.py`. Each day runs 08:15-20:00 in 15-minute steps.",
        "Plans are tested in the agent's *projected* day (real past + its own re-forecast); only approved",
        "plans touch the real day. Outcomes below are the **real** result from the first alert to close,",
        "against the same day with no action.",
        "",
        f"- **Checkpoint 1, recovers service level on 5 scenarios:** {len(recovered)} of {len(rows)} days improved by 5+ points.",
        f"- **Checkpoint 2, reject-and-re-plan works:** rejection \"{REJECTION}\" became constraints "
        f"`{ds.constraints.model_dump(exclude_defaults=True, exclude={'notes'})}`; overtime actions applied afterwards: "
        f"{len(ot_after)}.",
        "",
        "| Day | First alert | SL no action | SL with agent | Abandon no action | Abandon with agent | Action cost (Rs) | Planning rounds | Claude cost (US$) |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows + [dict(demo, sid="OUT-01 (rejects overtime)")]:
        s = r["session"]
        lines.append(f"| {r['sid']} | {s.first_alert} | {r['base'].service_level_pct}% | **{r['got'].service_level_pct}%** | "
                     f"{r['base'].abandon_rate_pct}% | {r['got'].abandon_rate_pct}% | {r['got'].action_cost_inr:,.0f} | "
                     f"{s.plans_made} | {r['claude_usd']:.2f} |")
    lines += ["", "Per-queue service level (no action -> agent):", ""]
    for r in rows + [dict(demo, sid="OUT-01 (rejects overtime)")]:
        q = {k: f"{r['base'].by_queue[k].service_level_pct}% -> {r['got'].by_queue[k].service_level_pct}%"
             for k in r["got"].by_queue}
        lines.append(f"- {r['sid']}: {q}")
    lines += ["", "## Demo day with the human moment (supervisor rejects overtime)", ""] + trace(ds)
    for r in rows:
        sc = get_scenario(r["sid"])
        lines += ["", f"## {r['sid']}: {sc.title}", ""] + trace(r["session"])
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}; Claude spend this run US${llm.usage.cost_usd:.2f}")


if __name__ == "__main__":
    main()
