"""Check every bad day is bad without action but rescuable; writes docs/calibration.md.

For each scenario we act 30 minutes after the trouble starts (roughly when an analyst
would notice) with a strong, hand-written response, and compare against doing nothing
and against the same day with no shock at all.

Run:  uv run python scripts/calibrate.py
"""

from __future__ import annotations

import numpy as np

from wfm.config import ROOT, load_centre, load_levers
from wfm.data.scenarios import load_scenarios
from wfm.schemas import (AppliedAction, CancelCoaching, ChatDeflection, DelayBreaks, IVRChange,
                         MoveAgents, OfferOvertime, Scenario)
from wfm.sim.day import prepare_scenario, run_day
from wfm.timegrid import hhmm_to_minutes, minutes_to_hhmm

OUT = ROOT / "docs" / "calibration.md"
OTHER = {"payments": "general", "general": "payments"}


def decision_time(sc: Scenario) -> str:
    start = hhmm_to_minutes(sc.shocks[0].start) + 30
    return minutes_to_hhmm(-(-start // 15) * 15)  # round up to the next 15-min tick


def shock_end(sc: Scenario) -> int:
    sh = sc.shocks[0]
    close = hhmm_to_minutes(load_centre().close_time)
    if sh.kind == "absence" or sh.duration_min is None:
        return close
    return min(close, hhmm_to_minutes(sh.start) + sh.duration_min + sh.decay_min)


def strong_response(sc: Scenario, t: str) -> list[AppliedAction]:
    """Cover the whole disruption: rolling 2-hour overtime blocks within the daily budget,
    callbacks and cross-skill moves for the full window, breaks and coaching pushed back."""
    sh = sc.shocks[0]
    close = load_centre().close_time
    t_min, end_min = hhmm_to_minutes(t), shock_end(sc)
    end = minutes_to_hhmm(end_min)
    acts = [DelayBreaks(window_start=t, window_end=minutes_to_hhmm(t_min + 90), delay_minutes=30),
            CancelCoaching(window_start=t, window_end=close)]
    ot = load_levers()["offer_overtime"]
    blocks = list(range(t_min, end_min, 120))
    per_block = ot["cost_inr_per_hour"] * 2 * ot["limits"]["acceptance_rate"]
    offered = min(25, int(ot["limits"]["daily_budget_inr"] / (per_block * len(blocks) * len(sh.queues))))
    for q in sh.queues:
        for b in blocks:
            if offered:
                acts.append(OfferOvertime(queue=q, start=minutes_to_hhmm(b),
                                          end=minutes_to_hhmm(min(b + 120, end_min + 30, hhmm_to_minutes(close))),
                                          agents_offered=offered))
        acts.append(IVRChange(queue=q, mode="callback", start=t, end=end))
    if len(sh.queues) == 1:
        q = sh.queues[0]
        acts.append(MoveAgents(from_queue=OTHER[q], to_queue=q, agents=8, start=t, end=end))
    if sh.kind == "volume" and sh.extra_reason_mix:
        q = sh.queues[0]
        top = [r for r, p in sh.extra_reason_mix.items() if p >= 0.2]
        if sc.type in ("outage_spike", "adversarial"):
            acts.append(IVRChange(queue=q, mode="outage_message", start=t, end=end, related_reasons=top))
        chat_ok = [r for r in top if r in load_levers()["chat_deflection"]["limits"]["eligible_reasons"]]
        if chat_ok:
            acts.append(ChatDeflection(queue=q, start=t, end=end, share=0.2, reasons=chat_ok))
    return [AppliedAction(decided_at=t, action=a) for a in acts]


def affected_sl(result, sc: Scenario, t: str) -> tuple[float, float]:
    """Service level and abandon rate from t to close on the queues the shock hits."""
    s = result.summary(t)
    qs = [s.by_queue[q] for q in sc.shocks[0].queues]
    denom = sum(q.answered + q.abandoned for q in qs) or 1
    sl = sum(q.service_level_pct * (q.answered + q.abandoned) for q in qs) / denom
    ab = sum(q.abandon_rate_pct * (q.answered + q.abandoned) for q in qs) / denom
    return round(sl, 1), round(ab, 1)


def main() -> None:
    rows = []
    for sc in load_scenarios():
        t = decision_time(sc)
        calm = run_day(prepare_scenario(sc.model_copy(update={"shocks": []})))
        none = run_day(sc.id)
        fixed = run_day(sc.id, strong_response(sc, t))
        rows.append(dict(id=sc.id, type=sc.type, t=t, calm=affected_sl(calm, sc, t)[0],
                         none=affected_sl(none, sc, t), fixed=affected_sl(fixed, sc, t),
                         cost=fixed.action_cost))

    lines = [
        "# Calibration: are the bad days bad, and can they be rescued?",
        "",
        "Generated by `uv run python scripts/calibrate.py`. Service level (SL) and abandon rate are",
        "measured from the decision time to close, on the queue(s) the disruption hits.",
        "",
        "- **Calm day**: the same date and callers with the disruption removed.",
        "- **No action**: the morning plan runs unchanged.",
        "- **Strong response**: a hand-written, policy-blind 'throw everything at it' plan at the",
        "  decision time (shock start + 30 min). It only proves the day is *rescuable*; it is not",
        "  the rule-based baseline and ignores cost.",
        "",
        "| Scenario | Type | Decide at | Calm-day SL | No-action SL | No-action abandon | Strong-response SL | Strong-response abandon | Response cost (Rs) |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(f"| {r['id']} | {r['type']} | {r['t']} | {r['calm']}% | {r['none'][0]}% | {r['none'][1]}% | "
                     f"{r['fixed'][0]}% | {r['fixed'][1]}% | {r['cost']:,.0f} |")
    none_sl = np.array([r["none"][0] for r in rows])
    fixed_sl = np.array([r["fixed"][0] for r in rows])
    lines += [
        "",
        f"**Averages:** calm {np.mean([r['calm'] for r in rows]):.1f}%, no action {none_sl.mean():.1f}%, "
        f"strong response {fixed_sl.mean():.1f}%.",
        f"Days failing the 80% promise with no action: {(none_sl < 80).sum()} of {len(rows)}. "
        f"Days the strong response lifts by 10+ points: {((fixed_sl - none_sl) >= 10).sum()} of {len(rows)}.",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print("\n".join(lines[11:]))


if __name__ == "__main__":
    main()
